export async function fetchProviderCompetitionDetails(slug: string): Promise<any> {
  try {
    const todayStr = new Date().toISOString().split('T')[0].replace(/-/g, '');
    const url = `https://site.api.espn.com/apis/site/v2/sports/soccer/${slug}/scoreboard?dates=${todayStr}`;
    const res = await fetch(url, {
      headers: {
        'User-Agent': 'Mozilla/5.0 (FootBuzz Football Platform)',
        Accept: 'application/json',
      },
    });

    if (res.ok) {
      const data = await res.json();
      const leagueMeta = data.leagues?.[0];
      return {
        slug,
        name: leagueMeta?.name || slug,
        shortName: leagueMeta?.abbreviation || slug,
        seasonYear: leagueMeta?.season?.year || new Date().getFullYear(),
        logoUrl: leagueMeta?.logos?.[0]?.href,
        eventsCount: Array.isArray(data.events) ? data.events.length : 0,
        providerId: leagueMeta?.id || slug,
      };
    }
  } catch (err) {
    console.error(`ESPN Competition Details Error for ${slug}:`, err);
  }

  return null;
}
